-- Cria a tabela de produtos: as mídias físicas de jogos à venda.
CREATE TABLE produtos (
    -- Cria uma chave numérica gerada automaticamente pelo PostgreSQL.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Nome obrigatório da mídia (ex.: "Fita Super Nintendo - Donkey Kong").
    nome VARCHAR(255) NOT NULL,
    -- Preço unitário em reais; precisa ser maior que zero.
    preco NUMERIC(10, 2) NOT NULL CHECK (preco > 0),
    -- Unidades em estoque. Nunca fica negativo: o banco é a última barreira contra venda sem estoque.
    estoque INTEGER NOT NULL DEFAULT 0 CHECK (estoque >= 0)
);
