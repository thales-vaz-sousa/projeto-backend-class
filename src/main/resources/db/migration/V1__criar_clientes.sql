-- Cria a tabela de clientes: as pessoas cadastradas na loja, cada uma com um saldo.
CREATE TABLE clientes (
    -- Cria uma chave numérica gerada automaticamente pelo PostgreSQL.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Guarda o nome obrigatório do cliente.
    nome VARCHAR(255) NOT NULL,
    -- Guarda o e-mail obrigatório do cliente.
    email VARCHAR(255) NOT NULL,
    -- Saldo em reais para comprar. Nasce zerado e o banco recusa saldo negativo.
    saldo NUMERIC(12, 2) NOT NULL DEFAULT 0 CHECK (saldo >= 0)
);
