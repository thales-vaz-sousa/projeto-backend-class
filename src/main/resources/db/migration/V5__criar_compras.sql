-- Cria a tabela de compras: o registro de um carrinho finalizado.
-- Vem depois de V1 e V3 porque referencia clientes e carrinhos.
CREATE TABLE compras (
    -- Cria uma chave numérica gerada automaticamente pelo PostgreSQL.
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Carrinho que virou compra. UNIQUE: um carrinho só pode ser pago uma vez.
                         carrinho_id BIGINT NOT NULL UNIQUE REFERENCES carrinhos (id),
    -- Quem comprou.
                         cliente_id BIGINT NOT NULL REFERENCES clientes (id),
    -- Total cobrado do saldo do cliente.
                         valor_total NUMERIC(12, 2) NOT NULL CHECK (valor_total >= 0),
    -- Dia em que a compra foi feita.
                         data_compra DATE NOT NULL
);
