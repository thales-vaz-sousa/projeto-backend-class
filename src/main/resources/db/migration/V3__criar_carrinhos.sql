-- Cria a tabela de carrinhos: cada carrinho pertence a um cliente.
-- Vem depois de V1 porque referencia clientes.
CREATE TABLE carrinhos (
    -- Cria uma chave numérica gerada automaticamente pelo PostgreSQL.
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Dono do carrinho. REFERENCES cria a chave estrangeira para clientes(id).
    cliente_id BIGINT NOT NULL REFERENCES clientes (id),
    -- Dia em que o carrinho foi aberto.
    data_criacao DATE NOT NULL,
    -- Vira verdadeiro quando a compra é finalizada; carrinho finalizado não aceita mais itens.
    finalizado BOOLEAN NOT NULL DEFAULT FALSE
);
