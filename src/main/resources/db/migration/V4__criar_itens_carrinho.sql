-- Cria a tabela de itens: cada linha é um produto dentro de um carrinho, com a quantidade.
-- Vem depois de V2 e V3 porque referencia as duas tabelas.
CREATE TABLE itens_carrinho (
    -- Cria uma chave numérica gerada automaticamente pelo PostgreSQL.
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Carrinho que contém o item.
                                carrinho_id BIGINT NOT NULL REFERENCES carrinhos (id),
    -- Produto colocado no carrinho.
                                produto_id BIGINT NOT NULL REFERENCES produtos (id),
    -- Quantas unidades; precisa ser pelo menos 1.
                                quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    -- O mesmo produto aparece uma vez por carrinho: repetir soma a quantidade.
                                UNIQUE (carrinho_id, produto_id)
);
